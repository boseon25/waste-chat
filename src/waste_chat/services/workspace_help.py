"""사용자가 화면을 어떻게 조작하는지 물을 때 현재 문서에서 가능한 동작을 안내한다."""
import re


# 화면 조작과 항목의 의미를 구분한다. 예를 들어 '이 칸에는 뭘 쓰나요?'는 항목 질문이다.
SELECT_FIELD = re.compile(
    r"(?:칸|항목|필드|목록|버튼|PDF)(?:하나|한개)?(?:만|을|를|에서|에)?(?:먼저|직접)?"
    r"(?:누르|누른|누름|눌|클릭|선택|고르|골|찍|지목|터치)|어디(?:를)?(?:누르|눌|클릭|터치)", re.I
)
INPUT_METHOD = re.compile(
    r"(?:값|내용|텍스트|것|거|부분|항목|칸)(?:들)?만(?:을|으로)?(?:입력|넣|적|쓰|써|채우|채워|보내)"
    r"|(?:채팅(?:창)?|대화(?:창)?|여기)(?:에|로|에서)(?:직접)?(?:입력|보내|쓰|써|치면|적으면)"
    r"|(?:입력|작성)(?:하는)?(?:방법|순서|방식)|사용(?:하는방법|법)|어떻게사용|^(?:어떻게)?쓰는법"
)
PARTIAL = re.compile(
    r"(?:아는|알고있는|내가가진|원하는|필요한|내가(?:입력|작성)할)(?:내용|정보|것|거|칸|부분|항목)?만"
    r"|(?:다|전부|모두)(?:입력|작성|채워)|(?:건너뛰|비워[둬도두]|보류|넘어가도|넘겨도)"
    r"|나중에(?:입력|작성|적어|쓰면|써도|채워)"
)
FIELD_CONTENT = re.compile(
    r"(?:뭘|무엇을?|뭐를?|뭐라고|어떤(?:값|내용|정보|이름|자료|수치))(?:을|를)?(?:입력|넣|적|쓰|써|기입|작성|채)"
    r"|(?:뜻|의미|기준|단위|예시|예를들|어디서확인|어디에서확인|뭔가요|뭔지|뭐야|뭐예요|뭐에요)"
    r"|(?:이칸|이항목|여기)(?:에는?|은|는)?(?:어떻게|무엇|뭐|뭘)"
    r"|(?:이름|명칭|번호|주소|숫자|단위)(?:만|도|까지)(?:입력|기입|적|쓰|써|넣|채)"
)


def is_input_problem(message):
    return re.search(r"(?:원본|pdf|칸|채팅|입력|클릭|선택).*(?:입력|작성|편집|수정|선택|클릭|저장)(?:이|이잘|을|을잘)?(?:안되|안돼|안됨|안되는|할수없)", re.sub(r"\s+", "", message), re.I)


def response(doc, message):
    phrase = re.sub(r"\s+", "", message).lower()
    if re.search(r"기초(?:정보|입력)|(?:외부|예시|샘플)json", phrase) and re.search(r"불러|가져|연결|이어|재사용|반영|읽|다른서류|연동", phrase):
        return ("‘작업 파일’ → ‘기초정보 불러오기’에서 JSON이나 Markdown 파일을 열고 배출 건 하나를 선택해 연결하세요. "
                "작성 중인 서류에서 빈칸을 선택하면 그 칸에 맞는 값과 출처가 보입니다. "
                "물량은 단위와 대상 기간을 확인한 후 ‘이 값 반영’을 누르세요.")
    cells = doc.get("original_cells", [])
    if cells and re.search(r"위치(?:를)?(?:이동|옮|찍)|(?:칸|항목)(?:을|를|만)?(?:그냥|직접|바로)?(?:지정|고르|눌|누르|선택)", phrase):
        if not FIELD_CONTENT.search(phrase):
            return "PDF에서 표시된 칸을 누르거나 작성 대화의 ‘작성할 칸’ 목록에서 항목을 고르세요. 그 칸에 넣을 값만 보내면 됩니다. 다른 칸을 바로 눌러 계속 작성하고 ‘작성 사본 PDF 저장’으로 내려받을 수 있습니다."
    computer = re.search(r"컴퓨터|타이핑|전자적|전자문서|pc로|pc에서", phrase)
    acceptance = re.search(r"제출해도|제출가능|효력|유효|인정|법적으로|서명|날인|직인", phrase)
    if (computer and re.search(r"작성|적어|채워|기입|입력|제출", phrase)) or acceptance:
        if doc["id"] == "analysis":
            return ("제13호의 상호·주소 등 제출인 정보는 컴퓨터로 준비할 수 있습니다. "
                    "지정폐기물 처리계획 확인에 필요한 분석결과서는 폐기물분석전문기관이 작성합니다(폐기물관리법 제17조제5항제2호). "
                    "배출업체는 기관이 작성한 결과서를 받아 제출하세요. 서식 맨 아래에는 ‘제출인’의 서명 또는 인을 요구합니다.")
        if doc["id"] == "form6":
            return ("제6호 신고서의 상호·주소 등은 컴퓨터로 채울 수 있습니다. 종이로 제출할 때는 신고인이 서명하거나 날인하세요. "
                    "정부24의 해당 배출자 신고 안내에는 인터넷·방문·우편 접수가 안내되어 있습니다. 온라인에서는 안내된 접수 절차를 따르세요.")
        return (doc["description"] + " 빈 양식의 기초 정보는 컴퓨터로 준비할 수 있습니다. "
                "제출할 때는 해당 서식에서 정한 작성 주체, 서명·날인, 접수 경로를 확인하세요.")
    if doc["id"] == "analysis":
        if re.search(r"함유량|용출|시험값|시험결과|⑪", phrase):
            return "⑪ 유해물질별 함유량에는 해당 폐기물의 용출시험 결과를 적습니다. 제출에 쓸 수치는 폐기물분석전문기관이 작성한 분석결과서에서 확인하세요(별지 제13호 작성방법 제3호)."
        if re.search(r"⑦|발생량", phrase):
            return "⑦ 발생량은 이 폐기물이 한 달에 얼마나 발생하는지 kg/월 단위로 적는 칸입니다. 해당 폐기물의 발생 기록을 확인하세요."
        if re.search(r"제출인|상호|사업자등록번호|대표자|사업장주소", phrase):
            return "제13호의 ①~⑤에는 제출인의 상호, 사업자등록번호, 대표자 성명과 생년월일, 사업장 주소와 전화번호를 적습니다. 서식 맨 아래에는 제출인의 서명 또는 인을 요구합니다."
    if is_input_problem(message) and ("원본" in phrase or "pdf" in phrase) and doc["fields"]:
        return ("이 서식의 미리보기에서는 표시된 칸을 선택하고 값을 채팅으로 보낼 수 있습니다. "
                "자동 입력 항목이 없는 동봉 원본은 문서 목록에서 열고 원본 페이지의 원하는 위치를 누르세요.")
    if re.search(r"(?:사진|캡처|스크린샷|이미지).*(?:첨부|붙여넣|올리|올려|올릴|업로드|인식|읽어)", phrase):
        result = "‘사진 첨부’에서 이미지를 고르거나 채팅창에 캡처를 붙여넣으세요."
        if doc["fields"]:
            return result + " 원하는 칸과 연결한 다음 사진을 보면서 값을 입력하고 ‘입력값 반영’을 누르세요. 사진의 글자는 직접 확인해야 합니다."
        return result + " 이 서류에서는 사진을 참고 자료로 보관할 수 있습니다."
    if re.search(r"(?:이전|아까|기존|전에|이미).*(?:가져|불러|재사용|복사|붙여|다시입력)|(?:자동입력|자동으로(?:채워|채우|입력))", phrase):
        if doc["fields"]:
            return ("다른 서류에 같은 항목이 있으면 빈칸을 선택했을 때 값과 출처가 보입니다. ‘이 값 반영’을 눌러야 복사됩니다. "
                    "예전에 채팅으로 보낸 문구는 ‘이전 대화에서 문구 가져오기’에서 선택할 수 있습니다.")
    if re.search(r"(?:작업|대화|작성한내용|이어서|나중에다시).*(?:저장|다시열|이어|불러오)|(?:저장하고|저장했다가).*이어서", phrase):
        return "‘작업 파일’에서 작업을 JSON으로 저장하세요. 나중에 같은 메뉴에서 그 파일을 열면 서류별 입력값·대화·첨부 사진을 이어서 볼 수 있습니다."
    if re.search(r"pdf.*(?:저장|다운|내려받)|(?:작성본|완성본).*(?:저장|다운|내려받)", phrase):
        if doc["fields"]:
            return "문서 미리보기에서 내용을 확인한 뒤 ‘PDF 저장’을 누르세요. 나중에 수정하려면 ‘작업 파일’에서 작업 JSON도 저장해 두세요."
        if doc.get("file"):
            return "문구를 넣은 후 ‘작성 사본 PDF 저장’을 누르세요. 빈 양식은 ‘원본 PDF 저장’으로 내려받을 수 있습니다."
    if doc.get("file") and not doc["fields"] and re.search(r"(?:원본|pdf).*(?:글자|입력|편집|수정|작성|채우|채워)", phrase):
        if cells:
            return "PDF에 표시된 칸이나 ‘작성할 칸’ 목록에서 항목을 선택하고 채팅에 값을 보내세요. 표시가 없는 위치는 ‘자유 배치’로 입력하세요. ‘작성 사본 PDF 저장’으로 내려받을 수 있습니다."
        return "원본 PDF에서 작성할 위치를 누르고 채팅으로 문구를 보내세요. 입력한 문구는 ‘작성 사본 PDF 저장’으로 내려받을 수 있습니다."
    if not (SELECT_FIELD.search(phrase) or INPUT_METHOD.search(phrase) or PARTIAL.search(phrase)):
        return None
    # '칸을 누르고 나서 여기에는 뭘 적나요?'도 실제 항목 설명을 요청한 것이다.
    if FIELD_CONTENT.search(phrase) and not PARTIAL.search(phrase):
        return None
    if not doc["fields"]:
        if cells:
            return "PDF에서 표시된 칸을 누르고 채팅에 값만 보내세요. 다음 칸도 바로 눌러 작성할 수 있습니다. ‘작성 사본 PDF 저장’으로 내려받으세요."
        if doc.get("file"):
            return "원본 PDF에서 작성할 위치를 누른 뒤 채팅에 그 위치에 넣을 값만 보내세요. 문구를 확인한 후 ‘작성 사본 PDF 저장’을 누르세요."
        return "이 문서는 자료 안내용입니다. 발급·확인한 내용은 ‘파일·접수 메모’에 남길 수 있습니다."
    reply = ("PDF에서 작성할 칸을 누른 뒤 채팅에 그 칸의 값만 보내면 됩니다. 항목 이름은 다시 쓰지 않아도 됩니다.")
    if PARTIAL.search(phrase):
        reply += " 초안은 아는 칸부터 작성하세요. 모르는 칸은 ‘나중에 확인’으로 남겨 두고 제출 전에 필요한 항목을 확인하세요."
    return reply
