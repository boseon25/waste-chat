def guidance(doc_id, field):
    """Return display guidance for a catalog field, without modifying the field or its value."""
    key = field["key"]
    help_text = _DOC_HELP.get((doc_id, key))
    if help_text is None and doc_id in {"form5_b", "form5_c"} and key == "waste_state_code":
        help_text = _FORM5_STATE
    if help_text is None:
        help_text = _FIELD_HELP.get(key)
    if help_text is None:
        role, _, name = key.partition("_")
        if role in _ROLE and name in _ROLE_HELP:
            help_text = _ROLE_HELP[name].format(role=_ROLE[role])
        else:
            help_text = f"‘{field['label']}’에 해당하는 값을 원자료 또는 담당자에게 확인해 입력합니다."
    info = {"help": help_text}
    if key in _EXAMPLES:
        info["example"] = _EXAMPLES[key]
    return info
